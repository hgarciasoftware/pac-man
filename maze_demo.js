export const TILE_SIZE = 30;
const PACMAN_IMAGE = new Image();

PACMAN_IMAGE.src = './pacman.png';

const angles = {
    up: 0,
    right: Math.PI / 2,
    down: Math.PI,
    left: -Math.PI / 2
};

function drawPacMan(facing) {
    const centerX = (player.renderX + 0.5) * TILE_SIZE;
    const centerY = (player.renderY + 0.5) * TILE_SIZE;

    ctx.save();
    ctx.translate(centerX, centerY);
    ctx.rotate(angles[facing]);
    ctx.drawImage(PACMAN_IMAGE, -TILE_SIZE / 2, -TILE_SIZE / 2, TILE_SIZE, TILE_SIZE);
    ctx.restore();
}

export function draw(maze, facing) {
    for (let i = 0; i < maze.length; i++) {
        for (let j = 0; j < maze[i].length; j++) {
            ctx.fillStyle = maze[i][j] == 0 ? '#1c1c1c' : '#2f2bff';
            ctx.fillRect(j * TILE_SIZE, i * TILE_SIZE, TILE_SIZE, TILE_SIZE);
        }
    }

    drawPellets();
    drawRedGhost();

    const pacManImageHasLoaded = PACMAN_IMAGE.complete && PACMAN_IMAGE.naturalWidth > 0;

    if (!gameOver && pacManImageHasLoaded) {
        drawPacMan(facing);
    }
}
